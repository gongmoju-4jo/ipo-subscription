--   → 기존 행의 값을 고쳐도 이미 만든 DB에는 반영되지 않는다. 새 행 추가는 반영된다
-- 종목이 모두 마감되면 PostgreSQL 볼륨을 초기화한다 (docs/PROJECT_SETUP.md 10장)
